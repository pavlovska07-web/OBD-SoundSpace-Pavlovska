SET client_encoding = 'UTF8';

DROP VIEW IF EXISTS v_future_bookings;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS equipment_conditions CASCADE;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS booking_equipment CASCADE;
DROP TABLE IF EXISTS bookings CASCADE;
DROP TABLE IF EXISTS administrators CASCADE;
DROP TABLE IF EXISTS equipment CASCADE;
DROP TABLE IF EXISTS rooms CASCADE;
DROP TABLE IF EXISTS bands CASCADE;

CREATE TABLE bands (
    band_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_name      VARCHAR(100) NOT NULL,
    genre          VARCHAR(50),
    contact_person VARCHAR(100) NOT NULL,
    phone          VARCHAR(20) NOT NULL,
    email          VARCHAR(100)
);

CREATE TABLE rooms (
    room_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_name   VARCHAR(50) NOT NULL UNIQUE,
    area_sqm    NUMERIC(5,2) CHECK (area_sqm > 0),
    capacity    INT CHECK (capacity > 0),
    hourly_rate NUMERIC(8,2) NOT NULL CHECK (hourly_rate >= 0),
    description VARCHAR(255)
);

CREATE TABLE equipment (
    equipment_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_name   VARCHAR(100) NOT NULL,
    category         VARCHAR(50) NOT NULL,
    rental_price     NUMERIC(8,2) NOT NULL CHECK (rental_price >= 0),
    inventory_number VARCHAR(50) DEFAULT 'INV-0000' NOT NULL
);

CREATE TABLE administrators (
    admin_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name  VARCHAR(100) NOT NULL,
    phone      VARCHAR(20) NOT NULL,
    shift_info VARCHAR(100)
);

CREATE TABLE bookings (
    booking_id   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    band_id      INT NOT NULL,
    room_id      INT NOT NULL,
    admin_id     INT,
    booking_date DATE NOT NULL,
    start_time   VARCHAR(20) NOT NULL,
    end_time     VARCHAR(20) NOT NULL,
    status       VARCHAR(30) DEFAULT 'Очікує' CHECK (status IN ('Очікує', 'Підтверджено', 'Завершено', 'Скасовано')),
    total_cost   NUMERIC(10,2) CHECK (total_cost >= 0),
    CONSTRAINT fk_bookings_band FOREIGN KEY (band_id) REFERENCES bands(band_id) ON DELETE CASCADE,
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms(room_id) ON DELETE CASCADE,
    CONSTRAINT fk_bookings_admin FOREIGN KEY (admin_id) REFERENCES administrators(admin_id) ON DELETE SET NULL
);

CREATE TABLE booking_equipment (
    booking_equipment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id           INT NOT NULL,
    equipment_id         INT NOT NULL,
    quantity             INT DEFAULT 1 CHECK (quantity > 0),
    CONSTRAINT fk_be_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_be_equipment FOREIGN KEY (equipment_id) REFERENCES equipment(equipment_id) ON DELETE CASCADE
);

CREATE TABLE payments (
    payment_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id     INT NOT NULL UNIQUE,
    amount         NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
    payment_date   DATE DEFAULT CURRENT_DATE NOT NULL,
    payment_method VARCHAR(50) CHECK (payment_method IN ('Готівка', 'Картка', 'Онлайн')),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id) ON DELETE CASCADE
);

CREATE TABLE equipment_conditions (
    condition_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id     INT NOT NULL,
    booking_id       INT NOT NULL,
    admin_id         INT NOT NULL,
    check_date       DATE DEFAULT CURRENT_DATE NOT NULL,
    condition_status VARCHAR(50) DEFAULT 'Справне' CHECK (condition_status IN ('Справне', 'Потребує обслуговування', 'Пошкоджено')),
    notes            VARCHAR(255),
    CONSTRAINT fk_ec_equipment FOREIGN KEY (equipment_id) REFERENCES equipment(equipment_id) ON DELETE CASCADE,
    CONSTRAINT fk_ec_booking FOREIGN KEY (booking_id) REFERENCES bookings(booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_ec_admin FOREIGN KEY (admin_id) REFERENCES administrators(admin_id)
);

CREATE TABLE users (
    user_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20) NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    band_id       INT,
    admin_id      INT,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_band FOREIGN KEY (band_id) REFERENCES bands(band_id) ON DELETE SET NULL,
    CONSTRAINT fk_users_admin FOREIGN KEY (admin_id) REFERENCES administrators(admin_id) ON DELETE SET NULL
);

CREATE OR REPLACE VIEW v_future_bookings AS
SELECT
    b.booking_id,
    bd.band_name,
    bd.contact_person,
    bd.phone AS band_phone,
    r.room_name,
    r.hourly_rate,
    TO_CHAR(b.booking_date, 'YYYY-MM-DD') AS booking_date,
    b.start_time,
    b.end_time,
    b.status AS booking_status,
    b.total_cost
FROM bookings b
JOIN bands bd ON b.band_id = bd.band_id
JOIN rooms r ON b.room_id = r.room_id
WHERE b.status = 'Підтверджено'
ORDER BY b.booking_date ASC, b.start_time ASC;


